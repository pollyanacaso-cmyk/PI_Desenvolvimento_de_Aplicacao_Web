const router = require('express').Router();
const controller = require('../controllers/clienteController');
const autenticarToken = require('../middlewares/autenticarToken');
const autorizarPorPerfil = require('../middlewares/autorizarPorPerfil');
router.get('/', autenticarToken, autorizarPorPerfil('admin'), controller.listar);
router.get('/:id', autenticarToken, autorizarPorPerfil('admin'), controller.buscarPorId);
router.post('/', controller.criar);
router.put('/:id', autenticarToken, autorizarPorPerfil('admin'), controller.atualizar);
router.delete('/:id', autenticarToken, autorizarPorPerfil('admin'), controller.remover);
module.exports = router;
